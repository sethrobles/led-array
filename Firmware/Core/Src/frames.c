static void clearFrame(uint8_t frame[32][32])
{
    memset(frame, 0, 32 * 32 * sizeof(uint8_t));
}

static void variableDelay(uint32_t baseDelay, uint32_t filled, uint32_t total)
{
    // Delay shrinks as `filled` grows.
    // max ~ baseDelay, min = 1 iteration.
    uint32_t loops = (baseDelay * (total - filled)) / total;
    if (loops < 1)
        loops = 1;

    for (volatile uint32_t d = 0; d < loops; ++d)
    {
        __NOP();  // optional; keeps compiler from optimizing loop away
    }
}


// A pixel that moves around the border's edge in a spiral pattern
void animateBorderDot(uint32_t baseDelayMs)
{
    const int N = 32;
    static uint8_t frame[32][32];

    clearFrame(frame);

    int top    = 0;
    int bottom = N - 1;
    int left   = 0;
    int right  = N - 1;

    uint32_t filled      = 0;
    const uint32_t total = (uint32_t)N * (uint32_t)N;

    while (top <= bottom && left <= right && filled < total)
    {
        int row, col;

        // 1) Go right across the top row
        for (col = left; col <= right && filled < total; ++col)
        {
            row = top;
            frame[row][col] = 1;
            ++filled;

            writeFrame(frame);
            variableDelay(baseDelayMs, filled, total);
        }
        ++top;

        // 2) Go down the right column
        for (row = top; row <= bottom && filled < total; ++row)
        {
            col = right;
            frame[row][col] = 1;
            ++filled;

            writeFrame(frame);
            variableDelay(baseDelayMs, filled, total);
        }
        --right;

        // 3) Go left across the bottom row
        if (top <= bottom)
        {
            for (col = right; col >= left && filled < total; --col)
            {
                row = bottom;
                frame[row][col] = 1;
                ++filled;

                writeFrame(frame);
                variableDelay(baseDelayMs, filled, total);
            }
            --bottom;
        }

        // 4) Go up the left column
        if (left <= right)
        {
            for (row = bottom; row >= top && filled < total; --row)
            {
                col = left;
                frame[row][col] = 1;
                ++filled;

                writeFrame(frame);
                variableDelay(baseDelayMs, filled, total);
            }
            ++left;
        }
    }

    // Done: full spiral drawn, function returns so you can run other animations.
}


static void borderIndexToCoord(int idx, int N, int *r, int *c)
{
    const int perim = 4 * N - 4;
    idx %= perim;
    if (idx < 0) idx += perim;

    if (idx < N) {
        // Top edge: (0, 0) -> (0, N-1)
        *r = 0;
        *c = idx;
        return;
    }
    idx -= N;

    if (idx < N - 1) {
        // Right edge: (1, N-1) -> (N-1, N-1)
        *r = 1 + idx;
        *c = N - 1;
        return;
    }
    idx -= (N - 1);

    if (idx < N - 1) {
        // Bottom edge: (N-1, N-2) -> (N-1, 0)
        *r = N - 1;
        *c = (N - 2) - idx;
        return;
    }
    idx -= (N - 1);

    // Left edge: (N-2, 0) -> (1, 0)
    *r = (N - 2) - idx;
    *c = 0;
}



// Four dots move along the border from each corner to its opposite corner.
void animateCornersAroundEdges(uint32_t baseDelayMs)
{
    const int N = 32;
    const int perimeter = 4 * N - 4;         // 124 for 32x32
    const int halfPerimeter = perimeter; // 62 for 32x32

    static uint8_t frame[32][32];

    // Starting indices on the perimeter for the 4 corners (clockwise)
    const int startIdx[4] = {
        0,          // top-left  (0, 0)
        N - 1,      // top-right (0, N-1)
        2 * N - 2,  // bottom-right (N-1, N-1)
        3 * N - 3   // bottom-left  (N-1, 0)
    };

    // We move each corner dot half the perimeter so it reaches its opposite corner.
    for (int step = 0; step <= halfPerimeter; ++step)
    {
        clearFrame(frame);

        for (int i = 0; i < 4; ++i)
        {
            int idx = startIdx[i] + step;  // no wrap; we stop at opposite corner

            int r, c;
            borderIndexToCoord(idx, N, &r, &c);
            frame[r][c] = 1;
        }

        writeFrame(frame);

        // Simple fixed delay; swap this for variableDelay(...) if you want speed-up
        HAL_Delay(baseDelayMs);
        // or:
        // variableDelay(baseDelayMs, (uint32_t)(step + 1), (uint32_t)(halfPerimeter + 1));
    }

    // Done: all four have reached their opposite corners.
}



// Four-dot diagonal animation: start as 2x2 in center, move out to corners.
void animateDiagonalDot(uint32_t baseDelayMs)
{
    const int N = 32;              // assumes even; works generically for even N
    static uint8_t frame[32][32];

    const int mid0 = (N / 2) - 1;  // e.g., 15 for 32x32
    const int mid1 = (N / 2);      // e.g., 16 for 32x32

    // Number of steps to go from center block to the corners
    const int maxSteps = mid0;     // 15 for 32x32 → 16 frames (0..15)

    for (int s = 0; s <= maxSteps; ++s)
    {
//        clearFrame(frame);

        // Compute positions for this step
        int tl_r = mid0 - s;
        int tl_c = mid0 - s;

        int tr_r = mid0 - s;
        int tr_c = mid1 + s;

        int bl_r = mid1 + s;
        int bl_c = mid0 - s;

        int br_r = mid1 + s;
        int br_c = mid1 + s;

        // Set the four dots
        frame[tl_r][tl_c] = 1; // top-left
        frame[tr_r][tr_c] = 1; // top-right
        frame[bl_r][bl_c] = 1; // bottom-left
        frame[br_r][br_c] = 1; // bottom-right

        writeFrame(frame);

        // If you want constant delay, use HAL_Delay(baseDelay) instead
        variableDelay(baseDelayMs, (uint32_t)(s + 1), (uint32_t)(maxSteps + 1));
    }

    // Done; returns so you can chain to another animation if you want.
}


